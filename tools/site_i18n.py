# Order shown in the language menu: the site's own two first, then the rest.
MENU_ORDER = ["en", "ar", "fr", "de", "es", "it", "pt", "nl", "ru", "tr",
              "ur", "hi", "bn", "id", "ms", "zh", "ja", "ko"]
NATIVE = {
    "en": "English", "ar": "العربية", "fr": "Français", "de": "Deutsch", "es": "Español",
    "it": "Italiano", "pt": "Português", "nl": "Nederlands", "ru": "Русский", "tr": "Türkçe",
    "ur": "اردو", "hi": "हिन्दी", "bn": "বাংলা", "id": "Bahasa Indonesia", "ms": "Bahasa Melayu",
    "zh": "简体中文", "ja": "日本語", "ko": "한국어",
}
RTL = {"ar", "ur"}
OG_LOCALE = {
    "fr": "fr_FR", "de": "de_DE", "es": "es_ES", "it": "it_IT", "pt": "pt_BR", "nl": "nl_NL",
    "ru": "ru_RU", "tr": "tr_TR", "ur": "ur_PK", "hi": "hi_IN", "bn": "bn_BD", "id": "id_ID",
    "ms": "ms_MY", "zh": "zh_CN", "ja": "ja_JP", "ko": "ko_KR",
}
SITE_URL = "https://qeuapps.com"


def load(lang):
    f = os.path.join(CONTENT, f"{lang}.json")
    if not os.path.exists(f):
        return None
    with open(f, encoding="utf-8") as fh:
        return json.load(fh)


def source():
    with open(os.path.join(CONTENT, "_source.json"), encoding="utf-8") as fh:
        return json.load(fh)


def live_langs():
    """Languages that have a translation file (only these get pages)."""
    return [L for L in LANGS if os.path.exists(os.path.join(CONTENT, f"{L}.json"))]


def translatable(url):
    """URLs (as rendered by build.py) that get a /<lang>/ copy."""
    if url.startswith(("/privacy/",)) and url != "/privacy/":
        return False            # per-app policies already exist in every language
    return not url.startswith(("/vault", "/admin", "/api"))


def privacy_langs(slug):
    d = os.path.join(ROOT, "content", "privacy", slug)
    return {f[:-5] for f in os.listdir(d) if f.endswith(".json")} if os.path.isdir(d) else set()


def lang_url(url, L):
    """The address of `url` in language L."""
    m = re.match(r"^/privacy/([a-z0-9-]+)/(?:[a-z]{2}/)?$", url)
    if m:
        return f"/privacy/{m.group(1)}/{L}/" if L in privacy_langs(m.group(1)) else f"/privacy/{m.group(1)}/en/"
    if url == "/404/" or url == "/404":
        url = "/"
    if L in ("en", "ar"):
        return url + "?lang=" + L
    return f"/{L}{url}" if translatable(url) else url


