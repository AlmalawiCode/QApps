def lang_menu(url, current=None):
    """The 🌐 language menu in the header. `current` None = the en/ar page."""
    live = set(live_langs()) | {"en", "ar"}
    items = []
    for L in MENU_ORDER:
        if L not in live:
            continue
        cur = ' aria-current="true"' if L == current else ""
        d = ' dir="rtl"' if L in RTL else ""
        items.append(f'<a href="{lang_url(url, L)}" data-set-lang="{L}" lang="{L}"{d}{cur}>{NATIVE[L]}</a>')
    label = NATIVE[current] if current else '<span data-en>English</span><span data-ar>العربية</span>'
    return (f'<details class="lang-menu"><summary class="lang-sum">🌐 {label}</summary>'
            f'<div class="lang-list">{"".join(items)}</div></details>')


def hreflang(url):
    if not translatable(url) or url in ("/404", "/404/"):
        return ""
    tags = [f'<link rel="alternate" hreflang="en" href="{SITE_URL}{url}">',
            f'<link rel="alternate" hreflang="ar" href="{SITE_URL}{url}">',
            f'<link rel="alternate" hreflang="x-default" href="{SITE_URL}{url}">']
    tags += [f'<link rel="alternate" hreflang="{L}" href="{SITE_URL}/{L}{url}">' for L in live_langs()]
    return "\n".join(tags)


# ---------------------------------------------------------------------------
# making the /<lang>/ copy of one page
# ---------------------------------------------------------------------------

def _tr(d, text, missing):
    key = norm(text)
    t = d.get(key)
    if t:
        return t
    if re.search(r"[A-Za-z]", re.sub(r"<[^>]+>", "", key)):
        missing.add(key)
    return text


def localize(doc, L, d, url, page_urls, missing):
    # 1) the language menu: current language named, links untouched
    doc = re.sub(r'<details class="lang-menu">.*?</details>', lambda m: lang_menu(url, L), doc, flags=re.S)
    # 1b) audience-only elements (YouTube playlists): keep the English one
    for a, b, c, e, tag, attrs in reversed(list(marked_elements(doc, 'data-only="ar"'))):
        doc = doc[:a] + doc[e:]
    doc = doc.replace(' data-only="en"', "")
    # 2) marked elements, outermost only, from the end so offsets stay valid
    spans = sorted([(a, b, c, e, t, at, "en") for a, b, c, e, t, at in marked_elements(doc, "data-en")] +
                   [(a, b, c, e, t, at, "ar") for a, b, c, e, t, at in marked_elements(doc, "data-ar")])
    outer, last_end = [], -1
    for sp in spans:
        if sp[0] >= last_end:
            outer.append(sp)
            last_end = sp[3]
    for a, b, c, e, tag, attrs, kind in reversed(outer):
        if kind == "ar":
            doc = doc[:a] + doc[e:]
        elif b == e:                                   # void element: drop the marker
            doc = doc[:a] + "<" + tag + re.sub(r"\s+data-en(?=[\s>/]|$)", "", attrs) + (" /" if doc[a:b].endswith("/>") else "") + ">" + doc[e:]
        else:
            attrs2 = re.sub(r"\s+data-en(?=[\s>/]|$)", "", attrs)
            doc = doc[:a] + f"<{tag}{attrs2}>" + _tr(d, doc[b:c], missing) + f"</{tag}>" + doc[e:]
    # 2b) <option data-en="X" data-ar="Y">X — Y</option>: show X translated; the
    #     data-en value stays English (it labels the message the owner receives)
    doc = re.sub(r'(<option\b[^>]*\sdata-en="([^"]*)"[^>]*>)[^<]*',
                 lambda m: m.group(1) + _html.escape(_tr(d, _html.unescape(m.group(2)), missing), quote=False), doc)
    # question / hint texts the suggest form shows (data-q-en, data-ph-en)
    doc = re.sub(r'(\sdata-(?:q|ph)-en)="([^"]*)"',
                 lambda m: f'{m.group(1)}="{_html.escape(_tr(d, _html.unescape(m.group(2)), missing))}"', doc)
    doc = re.sub(r'\sdata-(?:[a-z]+-)?ar="[^"]*"', "", doc)
    # texts inside scripts (suggest form messages): a small dictionary for T()
    js = {k: d[k] for k in js_strings() if d.get(k)}
    if js:
        doc = doc.replace("</head>", "<script>window.QAPPS_T=" + json.dumps(js, ensure_ascii=False).replace("</", "<\\/") + ";</script>\n</head>", 1)
    # 2c) app screenshots in this language (tools/site_screenshots.py), if made
    def shot(m):
        local = f"{m.group(1)}_{L}.webp"
        return local if os.path.exists(os.path.join(ROOT, local.lstrip("/"))) else m.group(0)
    doc = re.sub(r"(/assets/img/apps/[a-z0-9-]+/[a-z0-9_]+?)_en\.webp", shot, doc)
    # 3) <html>, scripts that switch en/ar, titles and descriptions
    m = re.search(r'data-title-en="([^"]*)"', doc)
    title = _tr(d, _html.unescape(m.group(1)), missing) if m else "Q Apps"
    doc = re.sub(r"<html\b[^>]*>", f'<html lang="{L}" dir="{"rtl" if L in RTL else "ltr"}" data-lang="{L}" data-fixed-lang>', doc, count=1)
    doc = re.sub(r"<script>\(function\(\)\{try\{var S=.*?</script>", "", doc, count=1, flags=re.S)
    doc = re.sub(r"<script>document\.addEventListener\('click',function\(e\)\{var b=e\.target\.closest&&e\.target\.closest\('\[data-lang-toggle\]'\).*?</script>", "", doc, count=1, flags=re.S)
    doc = re.sub(r"<title>.*?</title>", "<title>" + _html.escape(_html.unescape(re.sub(r"<[^>]+>", "", title)), quote=False) + "</title>", doc, count=1, flags=re.S)

    def attr_tr(m):
        return f'{m.group(1)}="{_html.escape(_tr(d, _html.unescape(m.group(2)), missing))}"'
    doc = re.sub(r'(<meta (?:name|property)="(?:description|og:title|og:description|twitter:title|twitter:description)" content)="([^"]*)"', attr_tr, doc)
    doc = re.sub(r'\b(alt|aria-label|placeholder|title)="([^"]*[A-Za-z][^"]*)"', attr_tr, doc)
    doc = doc.replace('<meta property="og:locale" content="en_US">', f'<meta property="og:locale" content="{OG_LOCALE[L]}">')
    doc = doc.replace('<meta property="og:locale:alternate" content="ar_SA">', "")
    # 4) canonical / og:url
    if url not in ("/404", "/404/"):
        doc = re.sub(r'(<link rel="canonical" href=")[^"]*"', rf'\g<1>{SITE_URL}/{L}{url}"', doc)
        doc = re.sub(r'(<meta property="og:url" content=")[^"]*"', rf'\g<1>{SITE_URL}/{L}{url}"', doc)

    # 5) links to our own translated pages get the /<lang> prefix
    def link(m):
        whole, q, href = m.group(0), m.group(1), m.group(2)
        if "data-set-lang" in whole:
            return whole
        path = re.split(r"[?#]", href)[0]
        rest = href[len(path):]
        if path in page_urls:
            new = f"/{L}{path}"
        elif re.match(r"^/privacy/[a-z0-9-]+/$", path):
            new = lang_url(path, L)
        else:
            return whole
        return whole.replace(f"href={q}{href}{q}", f"href={q}{new}{rest}{q}")
    doc = re.sub(r'<a\b[^>]*?href=(["\'])(/[^"\']*)\1[^>]*>', link, doc)
    return doc


def build_all():
    """Write every /<lang>/ page. Called by build.py after the en/ar pages.
    Returns the sitemap URLs of the new pages."""
    import shutil
    for L in LANGS:                       # nothing stale stays behind
        if os.path.isdir(os.path.join(ROOT, L)):
            shutil.rmtree(os.path.join(ROOT, L))
    pages = []
    for f in sorted(page_files()):
        rel = os.path.relpath(f, ROOT).replace(os.sep, "/")
        url = "/404" if rel == "404.html" else "/" + rel[:-len("index.html")]
        if translatable(url):
            pages.append((f, rel, url))
    page_urls = {u for _, _, u in pages if u != "/404"}
    out_urls, report = [], []
    for L in live_langs():
        d = load(L)
        missing = set()
        for f, rel, url in pages:
            doc = localize(open(f, encoding="utf-8").read(), L, d, url, page_urls, missing)
            out = os.path.join(ROOT, L, rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with open(out, "w", encoding="utf-8") as fh:
                fh.write(doc)
            if url != "/404":
                out_urls.append(f"{SITE_URL}/{L}{url}")
        report.append(f"{L}:{len(missing)}" if missing else L)
    if out_urls:
        print(f"Languages: {len(live_langs())} x {len(pages)} pages (missing strings: {' '.join(report)})")
    return out_urls


