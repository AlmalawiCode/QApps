"""site_i18n.py — the website in the apps' 18 store languages.

The English/Arabic pages at the root stay as they are (both languages in one
page, switched by data-lang). For every other language a single-language copy
of each page is written under /<lang>/… (e.g. /fr/apps/vault/): every element
marked data-en gets the translation of its English inner HTML, every element
marked data-ar is dropped, internal links get the /<lang> prefix and the
<html> tag gets the real lang/dir.

Translations live in content/site/<lang>.json: {"<English inner HTML>": "<translation>"}.
The source list of English strings is content/site/_source.json (written by
`python3 tools/site_i18n.py extract` after tools/build.py has run).
A string without a translation stays in English (the build reports how many).
"""
import html as _html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "content", "site")

# Pages that get a translated copy (paths relative to ROOT, generated by build.py).
SKIP_DIRS = ("admin", "api", "assets", "content", "docs", "functions", "lib", "migrations",
             "proposals", "tools", "workers", "vault", "vault-new", "countdown", "node_modules", ".git")

TAG_RE = re.compile(r"<(/?)([a-zA-Z][a-zA-Z0-9]*)\b([^>]*?)(/?)>", re.S)
VOID = {"br", "img", "input", "meta", "link", "hr", "source", "wbr", "area", "col", "embed", "param", "track"}


def _attr_has(attrs, name):
    # a bare marker (data-en), not a value attribute (data-en="…" on <option>)
    return re.search(r"(?:^|\s)" + re.escape(name) + r"(?=\s|/|$)", attrs) is not None


def marked_elements(doc, attr):
    """Yield (start, inner_start, inner_end, end, tag, attrs) for every element
    whose start tag carries `attr` (data-en / data-ar). Nested same-name tags
    are matched by depth."""
    for m in TAG_RE.finditer(doc):
        if m.group(1) or not _attr_has(m.group(3), attr):
            continue
        tag = m.group(2).lower()
        if tag in VOID or m.group(4):          # <img data-en …>: the tag alone
            yield m.start(), m.end(), m.end(), m.end(), tag, m.group(3)
            continue
        depth, pos = 1, m.end()
        for n in TAG_RE.finditer(doc, m.end()):
            if n.group(2).lower() != tag or tag in VOID or n.group(4):
                continue
            depth += -1 if n.group(1) else 1
            if depth == 0:
                yield m.start(), m.end(), n.start(), n.end(), tag, m.group(3)
                break


def norm(s):
    return re.sub(r"\s+", " ", s).strip()


def page_files():
    for dirpath, dirs, files in os.walk(ROOT):
        rel = os.path.relpath(dirpath, ROOT)
        top = rel.split(os.sep)[0]
        if top in SKIP_DIRS or top in LANGS:
            dirs[:] = []
            continue
        # per-app privacy policies are already published in every language
        if re.match(r"privacy/[a-z-]+(/|$)", rel.replace(os.sep, "/")):
            dirs[:] = []
            continue
        for f in files:
            if f == "index.html" or (rel == "." and f == "404.html"):
                yield os.path.join(dirpath, f)


def extract_strings(doc):
    doc = re.sub(r'<details class="lang-menu">.*?</details>', "", doc, flags=re.S)  # names are fixed
    out = []
    for s, i0, i1, e, tag, attrs in marked_elements(doc, "data-en"):
        t = norm(doc[i0:i1])
        if t and re.search(r"[A-Za-z]", re.sub(r"<[^>]+>", "", t)):
            out.append(t)
    m = re.search(r'data-title-en="([^"]*)"', doc)
    if m:
        out.append(norm(_html.unescape(m.group(1))))
    m = re.search(r'<meta name="description" content="([^"]*)"', doc)
    if m:
        out.append(norm(_html.unescape(m.group(1))))
    for m in re.finditer(r'\b(?:alt|aria-label|placeholder|title|data-en|data-q-en|data-ph-en)="([^"]*[A-Za-z][^"]*)"', doc):
        out.append(norm(_html.unescape(m.group(1))))
    return out


JS_FILES = ["assets/js/suggest.js"]


def js_strings():
    """Visitor-facing texts inside scripts: the first argument of T("en", "ar")."""
    out = []
    for f in JS_FILES:
        src = open(os.path.join(ROOT, f), encoding="utf-8").read()
        out += [norm(m.group(1)) for m in re.finditer(r'\bT\(\s*"((?:[^"\\]|\\.)*)"', src)]
    # inline page scripts that read window.QAPPS_T directly (tools/docmatic_page.py)
    out += ["Open all", "Close all"]
    return out


LANGS = ["fr", "de", "es", "tr", "ja", "ko", "id", "ms", "zh", "pt", "it", "ru", "nl", "ur", "bn", "hi"]


def extract():
    seen, order = {}, []
    for f in sorted(page_files()):
        for t in extract_strings(open(f, encoding="utf-8").read()):
            if t not in seen:
                seen[t] = os.path.relpath(f, ROOT)
                order.append(t)
    for t in js_strings():
        if t not in seen:
            seen[t] = "(script) " + ", ".join(JS_FILES)
            order.append(t)
    os.makedirs(CONTENT, exist_ok=True)
    with open(os.path.join(CONTENT, "_source.json"), "w", encoding="utf-8") as fh:
        json.dump({t: seen[t] for t in order}, fh, ensure_ascii=False, indent=1)
    chars = sum(len(t) for t in order)
    print(f"{len(order)} strings, {chars} characters -> content/site/_source.json")


