def tags_of(s):
    return sorted(re.findall(r"</?[a-zA-Z][a-zA-Z0-9]*", s))


def status():
    src = source()
    print(f"{'lang':5} {'done':>5} {'missing':>8} {'unused':>7}")
    for L in LANGS:
        d = load(L)
        if d is None:
            print(f"{L:5} {'—':>5} {len(src):>8} {'—':>7}   (no file)")
            continue
        done = sum(1 for k in src if d.get(k))
        unused = sum(1 for k in d if k not in src)
        print(f"{L:5} {done:>5} {len(src) - done:>8} {unused:>7}")


def check(langs=None):
    """Every translation keeps the same HTML tags as its English text, keeps
    the brand names, and is not left in English."""
    src = source()
    with open(os.path.join(CONTENT, "glossary.json"), encoding="utf-8") as fh:
        keep = json.load(fh)["keep_as_is"]
    bad = 0
    for L in langs or LANGS:
        d = load(L)
        if d is None:
            continue
        for k, v in d.items():
            if k not in src or not v:
                continue
            probs = []
            if tags_of(k) != tags_of(v):
                probs.append("tags differ")
            for term in keep:
                if term in k and term not in v:
                    probs.append(f"lost «{term}»")
            names_only = not re.search(r"[A-Za-z]{2,}", re.sub("|".join(map(re.escape, sorted(keep, key=len, reverse=True))), "", re.sub(r"<[^>]+>", "", k)))
            if len(k) > 25 and v.strip() == k.strip() and L not in ("id", "ms") and not names_only:
                probs.append("not translated")
            if probs:
                bad += 1
                print(f"{L}: {', '.join(probs)}\n   en: {k[:120]}\n   {L}: {v[:120]}")
    print("check: OK" if not bad else f"check: {bad} problem(s)")
    return bad


def missing_file(L, out):
    """Write the English strings that language L still lacks (to send to a translator)."""
    src, d = source(), load(L) or {}
    todo = {k: "" for k in src if not d.get(k)}
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(todo, fh, ensure_ascii=False, indent=1)
    print(f"{len(todo)} strings -> {out}")


def merge(L, path):
    """Merge a file of new translations {english: translation} into <lang>.json
    (kept in source order; strings no longer on the site are dropped)."""
    src, d = source(), load(L) or {}
    with open(path, encoding="utf-8") as fh:
        d.update({norm(k): v for k, v in json.load(fh).items() if v})
    out = {k: d[k] for k in src if d.get(k)}
    with open(os.path.join(CONTENT, f"{L}.json"), "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1)
    print(f"{L}: {len(out)}/{len(src)} strings")


if __name__ == "__main__":
    cmd, args = (sys.argv[1] if len(sys.argv) > 1 else "status"), sys.argv[2:]
    if cmd == "extract":
        extract()
    elif cmd == "status":
        status()
    elif cmd == "check":
        sys.exit(1 if check(args or None) else 0)
    elif cmd == "missing":
        missing_file(args[0], args[1])
    elif cmd == "merge":
        merge(args[0], args[1])
    else:
        print(__doc__)
